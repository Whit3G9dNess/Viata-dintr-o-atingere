/* Ordinea din listă. Româna prima, fiindcă e originalul; engleza a doua, fiindcă
   e limba pe care o are la îndemână cel mai des cine nu știe română; restul
   alfabetic după numele lor, nu după cod — cine caută „Magyar" îl caută la M.

   De ce **astea** și nu toate limbile lumii: rândurile din jucărie nu sunt
   „Salut" și „Continuă", sunt definiții de teorie a artei. O traducere
   aproximativă a definiției petei de culoare nu e o stângăcie, e o lecție
   greșită — iar o limbă pe care n-o putem reciti nici tu, nici eu, ar rămâne
   greșită fără să afle nimeni.

   Și mai e ceva, din cod: tot ce se scrie pe pânză se rupe în rânduri **după
   spații** (`text.split(' ')`, în patru locuri). Chineza, japoneza sau thailandeza
   n-au spații între cuvinte — textul lor ar ieși pe o linie, afară din casetă.
   Araba și ebraica se scriu de la dreapta la stânga, iar toate casetele, fișele
   și plăcuțele sunt așezate de la stânga. Alea două n-ar fi o traducere în plus,
   ar fi o rescriere a desenului. */
