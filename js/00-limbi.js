function schimbaLimba(cod) {
  if (!LIMBI[cod] || cod === limba) return false;
  limba = cod;
  try { localStorage.setItem('limba', cod); } catch (e) { /* fereastră privată */ }

  for (const s of stampilele()) {
    s.o.latime = 0;
    s.o.inaltime = 0;
  }
  /* Repictarea tuturor sălilor deodată e cel mai scump cadru din toată jucăria.
     Nu se pune la socoteala fluenței: altfel termometrul l-ar lua drept înec și
     ar coborî o treaptă de rezoluție, tocmai când jucătorul a apăsat un buton. */
  if (typeof uitaCadrul === 'function') uitaCadrul();
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = cod;
  }
  return true;
}

/* Ce limbă vorbim la prima deschidere: cea aleasă data trecută, sau cea a
   browserului, dacă o avem — iar dacă nu, româna. Nimeni nu trebuie să caute
   butonul ca să înțeleagă primul rând. */
function alegeLimbaDeLaInceput() {
  try {
    const pastrata = localStorage.getItem('limba');
    if (pastrata && LIMBI[pastrata]) { limba = pastrata; return; }
  } catch (e) { /* fereastră privată: mergem mai departe */ }

  const dinBrowser = (typeof navigator !== 'undefined' && navigator.language || '')
    .slice(0, 2).toLowerCase();
  if (LIMBI[dinBrowser]) limba = dinBrowser;
}

