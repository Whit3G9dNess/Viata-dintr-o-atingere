/* Textul, pe cheie. Dacă limba de acum n-o are, se întoarce româna; dacă nici ea
   n-o are, se întoarce chiar cheia — se vede de departe că lipsește ceva, în loc
   să rămână un gol care arată a scenă stricată. */
function T(cheie) {
  const d = LIMBI[limba] || LIMBI.ro;
  if (d && d[cheie] !== undefined) return d[cheie];
  if (LIMBI.ro && LIMBI.ro[cheie] !== undefined) return LIMBI.ro[cheie];
  return cheie;
}

